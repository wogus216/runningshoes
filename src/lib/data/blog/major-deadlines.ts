// ISO('2026-07-09') → 'M/D'('7/9'). SSOT 날짜를 본문 프로즈에 주입할 때 사용.
export function md(iso: string): string {
  const [, m, d] = iso.split('-');
  return `${Number(m)}/${Number(d)}`;
}

