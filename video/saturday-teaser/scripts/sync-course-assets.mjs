import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import sharp from 'sharp';
const project=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const root=path.resolve(project,'../..');
const output=path.join(project,'public/sonkeechung');
const archive=path.join(root,'public/images/marathon/sonkeechung-peace-marathon-2026');
await fs.mkdir(output,{recursive:true});
await Promise.all(['course.json','satellite-2025-11-12.jpg'].map(name=>fs.copyFile(path.join(root,'public/data/sonkeechung',name),path.join(output,name))));
await Promise.all(['sohn-1936-ceremony.webp','sohn-1936-ceremony-source.txt'].map(name=>fs.copyFile(path.join(archive,name),path.join(output,name))));
const hero=path.join(output,'hero.png');
try {await fs.access(hero);await sharp(hero).webp({quality:89}).toFile(path.join(output,'hero.webp'));}
catch {
  try {await fs.access(path.join(output,'hero.webp'));}
  catch {await fs.copyFile(path.join(root,'public/images/marathon/sonkeechung-peace-marathon-2026/course-preview.webp'),path.join(output,'hero.webp'));}
}
const data=JSON.parse(await fs.readFile(path.join(output,'course.json'),'utf8'));
const portraitCredit=await fs.readFile(path.join(output,'sohn-1936-ceremony-source.txt'),'utf8');
await fs.writeFile(path.join(output,'credits.txt'),[data.attribution,data.terrain.attribution,...data.caveats,Object.entries(data.sources).map(([k,v])=>`${k}: ${v}`).join('\n'),portraitCredit,'Fuel example: 4-hour even-pace finish; Amino Vital Amino Shot Perfect Energy 45g, carbohydrate 24.4g per sachet. Eight sachets during the race, starting after 20 minutes then every 30 minutes. Not official aid station locations; pre-race fuel and sports drinks excluded. Practice and adjust individually.','Product: https://ajinomoto.co.kr/default/product/aminovital/shot.php?sub=03_3&tit=03','Nutrition: https://www.ausport.gov.au/ais/nutrition/supplements/group_a/sports-foods2/sports-gels/how-and-when-do-i-use-it','Music: original deterministic ambient score generated by scripts/course-score.py; no third-party recording.'].join('\n\n'));
console.log('Course assets synchronized');
